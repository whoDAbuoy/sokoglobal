import 'server-only';
import { PDFDocument, StandardFonts, rgb, type PDFFont, type PDFPage } from 'pdf-lib';
import { winAnsi, type DocModel } from './model';

const A4: [number, number] = [595.28, 841.89];
const M = 48;
const INK = rgb(0.09, 0.09, 0.11);
const MUTED = rgb(0.38, 0.4, 0.45);
const LINE = rgb(0.86, 0.87, 0.9);
const BRAND = rgb(0.15, 0.39, 0.92);

/** Render an invoice / receipt model to an A4 PDF (standard fonts, no network, server only). */
export async function renderDocument(model: DocModel, meta: { subject: string }): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  doc.setTitle(`${model.title} ${model.number}`);
  doc.setSubject(meta.subject);
  doc.setAuthor('SokoGlobal');
  doc.setProducer('SokoGlobal');
  doc.setCreationDate(new Date());
  const page = doc.addPage(A4);
  const regular = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const [W, H] = A4;
  let y = H - M;

  const text = (p: PDFPage, s: string, x: number, yy: number, size = 10, font: PDFFont = regular, color = INK) =>
    p.drawText(winAnsi(s), { x, y: yy, size, font, color });
  const right = (p: PDFPage, s: string, xr: number, yy: number, size = 10, font: PDFFont = regular, color = INK) => {
    const t = winAnsi(s);
    p.drawText(t, { x: xr - font.widthOfTextAtSize(t, size), y: yy, size, font, color });
  };
  /** Truncate with "..." so a long product or company name never overflows its column. */
  const fit = (s: string, max: number, size: number, font = regular) => {
    const t = winAnsi(s);
    if (font.widthOfTextAtSize(t, size) <= max) return t;
    let n = t.length;
    while (n > 1 && font.widthOfTextAtSize(`${t.slice(0, n)}...`, size) > max) n -= 1;
    return `${t.slice(0, n)}...`;
  };

  // Header
  page.drawRectangle({ x: 0, y: H - 6, width: W, height: 6, color: BRAND });
  text(page, 'SokoGlobal', M, y - 8, 18, bold, BRAND);
  text(page, 'Escrow-protected B2B trade', M, y - 24, 9, regular, MUTED);
  right(page, model.title.toUpperCase(), W - M, y - 8, 16, bold);
  right(page, model.number, W - M, y - 24, 10, regular, MUTED);
  right(page, `Issued ${model.issued}`, W - M, y - 37, 9, regular, MUTED);
  right(page, `Status: ${model.status}`, W - M, y - 50, 9, bold);
  y -= 78;

  // Parties
  const colW = (W - 2 * M - 24) / 2;
  let maxLines = 0;
  model.parties.slice(0, 2).forEach((party, i) => {
    const x = M + i * (colW + 24);
    text(page, party.heading.toUpperCase(), x, y, 8, bold, MUTED);
    party.lines.forEach((l, j) => text(page, fit(l, colW, j === 0 ? 11 : 9.5, j === 0 ? bold : regular), x, y - 15 - j * 13, j === 0 ? 11 : 9.5, j === 0 ? bold : regular));
    maxLines = Math.max(maxLines, party.lines.length);
  });
  y -= 22 + maxLines * 13;

  // Facts grid (2 columns)
  page.drawLine({ start: { x: M, y }, end: { x: W - M, y }, thickness: 0.6, color: LINE });
  y -= 16;
  model.facts.forEach((f, i) => {
    const x = M + (i % 2) * (colW + 24);
    const yy = y - Math.floor(i / 2) * 26;
    text(page, f.label.toUpperCase(), x, yy, 7.5, bold, MUTED);
    text(page, fit(f.value, colW, 9.5), x, yy - 11, 9.5);
  });
  y -= Math.ceil(model.facts.length / 2) * 26 + 8;

  // Line items
  const cols = [M, W - M - 250, W - M - 160, W - M];
  page.drawRectangle({ x: M, y: y - 6, width: W - 2 * M, height: 20, color: rgb(0.95, 0.96, 0.98) });
  text(page, model.table.head[0], cols[0] + 6, y, 8.5, bold, MUTED);
  if (model.table.head[1]) right(page, model.table.head[1], cols[1] + 40, y, 8.5, bold, MUTED);
  if (model.table.head[2]) right(page, model.table.head[2], cols[2] + 70, y, 8.5, bold, MUTED);
  right(page, model.table.head[3], cols[3] - 6, y, 8.5, bold, MUTED);
  y -= 24;
  for (const row of model.table.rows) {
    text(page, fit(row[0], cols[1] - M - 20, 9.5), cols[0] + 6, y, 9.5);
    if (row[1]) right(page, row[1], cols[1] + 40, y, 9.5);
    if (row[2]) right(page, row[2], cols[2] + 70, y, 9.5);
    right(page, row[3], cols[3] - 6, y, 9.5);
    y -= 8;
    page.drawLine({ start: { x: M, y }, end: { x: W - M, y }, thickness: 0.4, color: LINE });
    y -= 14;
  }

  // Totals
  y -= 4;
  for (const t of model.totals) {
    const font = t.strong ? bold : regular;
    const size = t.strong ? 11 : 9.5;
    right(page, t.label, W - M - 120, y, size, font, t.strong ? INK : MUTED);
    right(page, t.value, W - M - 6, y, size, font);
    y -= t.strong ? 20 : 15;
  }

  // Notes + footer
  y -= 10;
  for (const n of model.notes) { text(page, fit(n, W - 2 * M, 8.5), M, y, 8.5, regular, MUTED); y -= 12; }
  page.drawLine({ start: { x: M, y: M + 14 }, end: { x: W - M, y: M + 14 }, thickness: 0.4, color: LINE });
  text(page, `${model.number} · generated by SokoGlobal · ${model.issued}`, M, M, 7.5, regular, MUTED);

  return doc.save();
}

export function pdfResponse(bytes: Uint8Array, filename: string): Response {
  return new Response(Buffer.from(bytes), {
    headers: {
      'Content-Type': 'application/pdf',
      'Content-Disposition': `attachment; filename="${filename.replace(/[^A-Za-z0-9._-]/g, '_')}"`,
      'Cache-Control': 'private, no-store',
      'X-Content-Type-Options': 'nosniff',
    },
  });
}
