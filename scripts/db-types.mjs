#!/usr/bin/env node
/**
 * Regenerates lib/supabase/database.types.ts from the migrations (needs Docker): applies schema.sql and
 * every migration to a throwaway postgres:15 (scripts/db-docker.mjs), then runs `supabase gen types`
 * against it. Run after adding a migration; CI's `npm run db:types:check` fails if the file is stale.
 *
 *   npm run db:types
 *   npm run db:types:check   # exit 1 when the committed file differs from the migrations
 */
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { startDb } from './db-docker.mjs';

const SUPABASE_CLI = 'supabase@2.54.11';
// The image `supabase gen types` runs (it follows the CLI version above). The CLI pulls it from public.ecr.aws,
// which refuses anonymous pulls from busy CI runners ("toomanyrequests: Data limit exceeded"). Supabase publishes
// the same image on Docker Hub, so fetch it from there and tag it with the name the CLI looks for: the CLI then
// finds it locally and never pulls.
const PG_META = 'supabase/postgres-meta:v0.93.1';
const out = join(import.meta.dirname, '..', 'lib', 'supabase', 'database.types.ts');
const check = process.argv.includes('--check');
const port = Number(process.env.DB_TYPES_PORT || 54330);

/**
 * Postgres function arguments are always nullable (and `default null` ones are how the RPCs take
 * "not given"), but `supabase gen types` types them as non-null. Adds `| null` to every argument in
 * the public Functions section, so passing null type-checks without casts at each call.
 */
function nullableArgs(text) {
  const lines = text.split('\n');
  const prop = (p) => {
    const m = /^(\s*[\w]+\??): (.+)$/.exec(p);
    return !m || /\|\s*null$/.test(m[2]) ? p : `${m[1]}: ${m[2]} | null`;
  };
  let inFunctions = false;
  let closeArgs = null;   // the closing line of a multi-line Args block
  for (let i = 0; i < lines.length; i += 1) {
    const line = lines[i];
    if (/^ {4}Functions: \{$/.test(line)) { inFunctions = true; continue; }
    if (inFunctions && /^ {4}\w+: \{$/.test(line)) inFunctions = false;
    if (!inFunctions) continue;
    if (closeArgs !== null) {
      if (line === closeArgs) closeArgs = null;
      else lines[i] = prop(line);
      continue;
    }
    // One-line Args, alone or with Returns on the same line: `Args: { p_a: string; p_b?: number }`.
    lines[i] = line.replace(/Args: \{ ([^{}]*) \}/g, (_, inner) => `Args: { ${inner.split('; ').map(prop).join('; ')} }`);
    const open = /^(\s*)Args: \{$/.exec(line);
    if (open) closeArgs = `${open[1]}}`;
  }
  return lines.join('\n');
}

function prefetchPgMeta() {
  const docker = (args) => spawnSync('docker', args, { encoding: 'utf8' });
  const ecr = `public.ecr.aws/${PG_META}`;
  if (docker(['image', 'inspect', ecr]).status === 0) return;
  if (docker(['pull', '-q', PG_META]).status === 0) docker(['tag', PG_META, ecr]);
  // Otherwise the CLI tries public.ecr.aws itself, as before.
}

let exit = 0;
let db;
try {
  prefetchPgMeta();
  db = startDb(`sokoglobal-dbtypes-${process.pid}`, { port });
  db.applySchema();
  const gen = spawnSync('npx', ['-y', SUPABASE_CLI, 'gen', 'types', 'typescript', '--schema', 'public',
    '--db-url', `postgresql://postgres:pg@localhost:${port}/postgres`], { encoding: 'utf8', shell: process.platform === 'win32', maxBuffer: 64 * 1024 * 1024 });
  if (gen.status !== 0 || !gen.stdout.includes('export type Database')) throw new Error(`supabase gen types failed:\n${gen.stderr}`);
  const types = `// Generated by \`npm run db:types\` from supabase/schema.sql + supabase/migrations. Do not edit by hand.\n${nullableArgs(gen.stdout.replace(/\r\n/g, '\n'))}`;
  if (check) {
    let current = '';
    try { current = readFileSync(out, 'utf8').replace(/\r\n/g, '\n'); } catch { /* missing */ }
    if (current !== types) { console.error('✖ lib/supabase/database.types.ts is out of date: run `npm run db:types`'); exit = 1; }
    else console.log('✔ database types match the migrations');
  } else {
    writeFileSync(out, types);
    console.log(`✔ wrote ${out}`);
  }
} catch (err) {
  console.error(err instanceof Error ? err.message : err);
  exit = 1;
} finally {
  db?.remove();
}
process.exit(exit);
